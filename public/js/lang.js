// ---- Active language ----
let currentLang = (() => { try { return localStorage.getItem('sn_lang') || 'en'; } catch(e) { return 'en'; } })();

function setLang(code) {
  currentLang = code;
  try { localStorage.setItem('sn_lang', code); } catch(e) {}
  document.documentElement.lang = code === 'zh' ? 'zh-Hans' : code === 'ms' ? 'ms' : 'en';
}

function t(key) {
  return (LANG_DATA[currentLang] && LANG_DATA[currentLang][key] !== undefined)
    ? LANG_DATA[currentLang][key]
    : (LANG_DATA['en'][key] !== undefined ? LANG_DATA['en'][key] : key);
}
